async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const results = [];
  await page.goto('http://127.0.0.1:3001');
  await page.evaluate(() => { localStorage.removeItem('scenecaptions.profile.v1'); });
  await page.reload();
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.waitForFunction(() => document.querySelector('video').readyState >= 1);
  const track = await (await page.request.get('http://127.0.0.1:3001/research/demo-captions.json')).json();
  assert(track.generated_with.kind === 'sourced', 'Playback must use the licensed source track');
  assert(await page.locator('.cue-row').count() === 87, 'All source intervals installed');
  await page.getByText('Sourced sound captions.', { exact: true }).waitFor();
  assert(await page.getByLabel('Expressiveness', { exact: false }).isEnabled(), 'Expression variants are usable');
  assert(await page.getByLabel('Follow cue density', { exact: true }).isEnabled(), 'Cue-density adaptation available');
  await page.getByRole('button', { name: 'Original baseline', exact: true }).click();
  // Verify every interval renders its exact stored original after an actual media seek.
  for (const cue of track.cues) {
    await page.evaluate(seconds => { document.querySelector('video').currentTime = seconds; }, (cue.start_s + cue.end_s) / 2);
    await page.waitForFunction(expected => document.querySelector('.caption-lines')?.textContent === expected, cue.original_text);
  }
  results.push('all 87 source intervals render after real video seeks, including multiline effects and the final cue');
  await page.evaluate(() => { document.querySelector('video').currentTime = 78; });
  await page.waitForFunction(() => Math.abs(document.querySelector('video').currentTime - 78) < 0.1 && !document.querySelector('.caption-overlay'));
  await page.getByText('Next sound caption at 1:23', { exact: true }).waitFor();
  results.push('former 1:18 mismatch absent; next-cue timing explains the gap');
  await page.getByRole('button', { name: 'Personalized', exact: true }).click();
  await page.getByLabel('Follow cue density', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Apply preferences', exact: true }).click();
  const apple = track.cues.find(c => c.original_text === '[APPLE THUDS]');
  const appleIndex = track.cues.indexOf(apple);
  await page.locator('.cue-row').nth(appleIndex).click();
  await page.waitForFunction(expected => document.querySelector('.caption-lines')?.textContent === expected, apple.grid['2-2']);
  await page.getByRole('button', { name: 'Rich', exact: true }).click();
  assert(await page.locator('.caption-lines').textContent() === apple.grid['2-2'], 'Preview does not mutate applied caption');
  await page.getByRole('button', { name: 'Apply preferences', exact: true }).click();
  await page.waitForFunction(expected => document.querySelector('.caption-lines')?.textContent === expected, apple.grid['3-3']);
  await page.getByRole('button', { name: 'Show original', exact: true }).click();
  assert(await page.locator('.caption-lines').textContent() === apple.original_text, 'Original overrides personalization');
  await page.getByRole('button', { name: 'Original on', exact: true }).click();
  await page.getByRole('button', { name: 'Essential', exact: true }).click();
  await page.getByRole('button', { name: 'Apply preferences', exact: true }).click();
  await page.waitForFunction(expected => document.querySelector('.caption-lines')?.textContent === expected, apple.grid['1-1']);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('video').readyState >= 1);
  assert(await page.getByLabel('Level of detail', { exact: false }).inputValue() === '1', 'Applied preferences survive reload');
  await page.locator('.cue-row').nth(appleIndex).click();
  await page.waitForFunction(expected => document.querySelector('.caption-lines')?.textContent === expected, apple.grid['1-1']);
  await page.locator('video').focus();
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(seconds => Math.abs(document.querySelector('video').currentTime - seconds) < 0.05, apple.start_s);
  await page.locator('.cue-row').first().click();
  await page.getByRole('button', { name: 'Play video', exact: true }).first().click();
  await page.waitForFunction(() => !document.querySelector('video').paused && document.querySelector('video').currentTime > 2.7);
  await page.getByRole('button', { name: 'Pause video', exact: true }).click();
  results.push('play/pause, cue jump, original override, preview/apply, preferences persist, keyboard seeking');
  await page.getByRole('button', { name: 'Balanced', exact: true }).click();
  await page.getByLabel('Follow cue density', { exact: true }).check();
  await page.getByRole('button', { name: 'Apply preferences', exact: true }).click();
  const dense = track.cues.find(c => c.scene_load === 'dense');
  await page.locator('.cue-row').nth(track.cues.indexOf(dense)).click();
  await page.waitForFunction(expected => document.querySelector('.caption-lines')?.textContent === expected, dense.grid['1-2']);
  await page.getByRole('button', { name: 'Why this caption?', exact: true }).click();
  await page.getByText('Less detail among frequent sound cues', { exact: true }).waitFor();
  results.push('cue-density adaptation and explicit rationale');
  await page.getByLabel('Choose local video', { exact: true }).setInputFiles('public/media/big-buck-bunny.mp4');
  await page.waitForFunction(() => document.querySelector('video').src.startsWith('blob:') && document.querySelector('video').readyState >= 1);
  assert(await page.locator('.cue-row').count() === 0, 'New video clears sample captions');
  assert(await page.getByLabel('Level of detail', { exact: false }).isDisabled(), 'No controls without a matching track');
  assert(await page.getByText('Original mode uses fixed captions.', { exact: false }).count() === 0, 'No misleading baseline notice without captions');
  await page.getByLabel('Choose caption JSON', { exact: true }).setInputFiles('public/research/caption-template.json');
  await page.getByRole('alert').filter({ hasText: 'does not match' }).waitFor();
  assert(await page.locator('.caption-overlay').count() === 0, 'Duration mismatch suppresses overlay');
  const failed = { ...track, generated_with: { ...track.generated_with, quality_gate: 'failed' } };
  await page.getByLabel('Choose caption JSON', { exact: true }).setInputFiles({ name: 'failed.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(failed)) });
  await page.getByRole('alert').filter({ hasText: 'Failed generation candidates cannot be used for playback' }).waitFor();
  await page.getByLabel('Choose caption JSON', { exact: true }).setInputFiles('data/captions/big-buck-bunny.json');
  await page.waitForFunction(() => document.querySelectorAll('.cue-row').length === 87);
  await page.getByRole('button', { name: 'Restore sample film', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('video').src.startsWith('blob:') && document.querySelector('video').readyState >= 1);
  results.push('local media clears captions, correct unavailable notice, mismatch suppression, failed candidate rejection, matching import and restoration');
  assert(await page.getByRole('button', { name: 'Start rehearsal', exact: false }).isDisabled(), 'Opt-in required');
  await page.getByLabel('I agree to record this demo’s player interactions locally.').check();
  await page.getByRole('button', { name: 'Start rehearsal', exact: false }).click();
  await page.locator('.cue-row').nth(appleIndex).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export rehearsal JSON', exact: false }).click();
  const download = await downloadPromise; await download.saveAs('docs/verification/audit-2026-10-24/exports/sourced-rehearsal-test.json');
  await page.getByRole('button', { name: 'Stop recording', exact: true }).click();
  results.push('opt-in rehearsal and export');
  await page.reload(); await page.waitForFunction(() => document.querySelector('video').readyState >= 1);
  await page.locator('.cue-row').nth(appleIndex).click();
  await page.locator('.caption-lines').waitFor();
  await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: 'docs/verification/audit-2026-10-24/screenshots/sourced-captions-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No mobile horizontal overflow');
  await page.screenshot({ path: 'docs/verification/audit-2026-10-24/screenshots/sourced-captions-mobile.png', fullPage: true });
  await page.getByRole('link', { name: 'Experimental plan', exact: true }).click();
  await page.getByRole('heading', { name: 'How we’ll study it.', exact: true }).waitFor();
  results.push('mobile layout and experimental plan');
  return { passed: results };
}
